using ArithmeticVoronoi, Oscar, JSON3, Test
const SLAV=ArithmeticVoronoi

@testset "determinant quotient and full projective scalars" begin
    P=arithmetic_problem(5);units=SLAV.verified_units(P);epsilon=units.epsilon
    for n in (3,4,5),q in 0:2n-1,image in 0:2n-1,s in (-1,1)
        unit(k)=(-one(P.field))^mod(k,2)*epsilon^div(k,2)
        next=SLAV.determinant_coset(q,image,s,2,n)
        # The encoded cosets agree exactly modulo <epsilon^n>, including inverses.
        ratio=SLAV.unit_coordinates(P,units,unit(q)*unit(image)^s/unit(next))
        @test ratio.sign==0 && mod(ratio.exponent,n)==0
    end
    P=arithmetic_problem(-4;rank=4);I=identity_matrix(P.field,4)
    @test SLAV.projective_scalar(P.generator*I,I)==P.generator
    @test isnothing(SLAV.projective_scalar(2I,I))
    J=identity_matrix(P.field,3)
    @test isnothing(SLAV.projective_scalar(P.generator*J,J))
    T=simplify_matrix_presentation([P.generator*I],[[1]];projective=true)
    @test isempty(T.generator_matrices)
    @test verify_simplification([P.generator*I],[[1]],T)
    # The historical export format must not silently label a new rank as two.
    mktempdir() do root
        for P in (classical_problem(rank=3),arithmetic_problem(5;rank=3),arithmetic_problem(-4))
            directory=joinpath(root,"archive")
            R=(;enumeration=(;problem=P))
            @test_throws ArgumentError export_dataset(Dict(P.discriminant=>R);directory)
            @test !ispath(directory)
        end
    end
end

function test_sl_presentations(;cases=((1,2),(1,3),(-4,3),(-3,3)))
    @testset "SL and PSL presentations in arbitrary rank" begin
        for (D,n) in cases
            mktempdir() do directory
                P=D==1 ? classical_problem(;rank=n) : arithmetic_problem(D;rank=n)
                R=run_field_pipeline(P;directory)
                I=identity_matrix(P.field,n);S=R.sl;Q=R.psl
                @test verify_presentation(R.gl) && verify_sl_presentation(S)
                @test S.center_order==gcd(n,S.units.torsion_order)
                @test SLAV.evaluate_word(S.generator_matrices,S.center_word)==S.center_generator*I
                @test iseven(n) ? SLAV.evaluate_word(S.generator_matrices,S.minus_identity_word)==-I : isnothing(S.minus_identity_word)
                @test all(g->det(g)==1,S.generator_matrices)
                @test length(Q.relators)==length(S.relators)+(S.center_order>1)
                for (w,z) in zip(Q.relators,Q.relator_scalars)
                    @test z^n==1
                    @test SLAV.evaluate_word(Q.generator_matrices,w)==z*I
                end
                for target in (:SL,:PSL)
                    h1=R.run["presentations"][string(target)]["abelianization"]
                    @test h1.free_rank==0
                    # Z and the quadratic orders in these cases (including O_5)
                    # are Euclidean.
                    # SL_n is generated by elementary commutators for n >= 3.
                    @test h1.torsion==(n==2 && D==1 ? (target==:SL ? ["12"] : ["6"]) : String[])
                    @test verify_simplification(getproperty(R,target==:SL ? :sl : :psl).generator_matrices,
                        getproperty(R,target==:SL ? :sl : :psl).relators,R.simplified[target])
                end
                g=deepcopy(I);g[1,n]=P.degree==1 ? P.field(2) : P.generator
                h=deepcopy(I);h[n,1]=one(P.field)
                z=S.units.rank==0 ? S.units.torsion_generator : S.units.epsilon
                diagonal=deepcopy(I);diagonal[1,1]=z;diagonal[n,n]=inv(z)
                for matrix in (g,inv(g),g*h*inv(g)*inv(h),diagonal,S.center_generator*I),target in (:SL,:PSL),simplified in (false,true)
                    c=matrix_to_word(R,matrix;target,simplified)
                    @test verify_word_certificate(R,matrix,c)
                    legacy=deepcopy(c);legacy["schema"]="av_constructive_word_v1"
                    delete!(legacy,"SL_lift_scalar")
                    if isnothing(c["SL_lift_sign"])
                        @test_throws ArithmeticValidationError verify_word_certificate(R,matrix,legacy)
                    else
                        @test verify_word_certificate(R,matrix,legacy)
                    end
                    bad=deepcopy(c);bad["SL_lift_scalar"]=["0" for _ in 1:P.degree]
                    @test_throws ArithmeticValidationError verify_word_certificate(R,matrix,bad)
                end
                isodd(n) && @test_throws WordReductionError matrix_to_word(R,-I;target=:SL)
                cache=joinpath(directory,"central_word.json")
                c=matrix_to_word(R,S.center_generator*I;target=:PSL,cache_path=cache)
                @test matrix_to_word(R,S.center_generator*I;target=:PSL,cache_path=cache)["cache_replay"]
                @test JSON3.read(read(joinpath(directory,"PSL_raw.json"),String))["center_order"]==S.center_order
                if D==-3 && n==3
                    @test S.center_order==3 && S.center_generator!=1 && S.center_generator!=-1
                    @test any(isnothing,Q.relator_signs)
                    @test !isnothing(SLAV.projective_scalar(S.center_generator*I,I))
                end
            end
        end
    end
end

if abspath(PROGRAM_FILE)==@__FILE__
    test_sl_presentations()
end
